import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

import {
  lockfileParserFor,
  parseBunLock,
  parsePackageLock,
  parsePipfileLock,
  parsePnpmLock,
  parsePythonTomlLock,
  parseYarnLock,
} from "./lockfiles.js";

/** The 15 packages npm and pnpm both resolve for { lodash 4.17.15, @babel/code-frame 7.0.0, debug 2.6.8 }. */
const REAL_FIXTURE_PACKAGES = 15;

const summarize = (packages: ReturnType<typeof parsePackageLock>): string[] =>
  packages.map((pkg) => `${pkg.ecosystem}:${pkg.name}@${pkg.version} L${String(pkg.line)}`);

/** Reads a committed lockfile fixture (real files generated by npm 10 and pnpm 10). */
function fixture(name: string): string {
  // eslint-disable-next-line security/detect-non-literal-fs-filename -- test reads its own committed fixtures
  return readFileSync(new URL(`../../../tests/fixtures/lockfiles/${name}`, import.meta.url), "utf8");
}

describe("real lockfiles", () => {
  it("reads every package from an npm v3 package-lock.json, with the line of each entry", () => {
    const packages = parsePackageLock(fixture("package-lock.json"));

    expect(packages).toHaveLength(REAL_FIXTURE_PACKAGES);
    expect(summarize(packages)).toContain("npm:lodash@4.17.15 L" + String(packages.find((pkg) => pkg.name === "lodash")?.line));
    expect(packages.map((pkg) => pkg.name)).toEqual(expect.arrayContaining(["lodash", "debug", "ms", "@babel/code-frame"]));
    expect(packages.every((pkg) => pkg.line > 1)).toBe(true);
  });

  it("reads the same packages from the pnpm v9 lockfile", () => {
    const npm = parsePackageLock(fixture("package-lock.json")).map((pkg) => `${pkg.name}@${pkg.version}`);
    const pnpm = parsePnpmLock(fixture("pnpm-lock.yaml")).map((pkg) => `${pkg.name}@${pkg.version}`);

    expect(pnpm.sort()).toEqual(npm.sort());
  });
});

describe("parsePackageLock", () => {
  it("reads nested node_modules paths and skips links and the root", () => {
    const lock = JSON.stringify(
      {
        lockfileVersion: 3,
        packages: {
          "": { name: "app" },
          "node_modules/a": { version: "1.0.0" },
          "node_modules/a/node_modules/@s/b": { version: "2.0.0" },
          "node_modules/local": { link: true },
          "packages/web": { version: "0.0.0" },
        },
      },
      null,
      2,
    );

    expect(summarize(parsePackageLock(lock))).toEqual(["npm:a@1.0.0 L7", "npm:@s/b@2.0.0 L10"]);
  });

  it("reads lockfileVersion 1 nested dependencies", () => {
    const lock = JSON.stringify({ lockfileVersion: 1, dependencies: { a: { version: "1.0.0", dependencies: { b: { version: "2.0.0" } } } } }, null, 2);

    expect(summarize(parsePackageLock(lock)).map((entry) => entry.split(" ")[0])).toEqual(["npm:a@1.0.0", "npm:b@2.0.0"]);
  });

  it("returns [] for invalid JSON", () => {
    expect(parsePackageLock("{ nope")).toEqual([]);
  });
});

describe("parsePnpmLock", () => {
  it("reads v6 keys with leading slashes, v9 peer suffixes, and v5 name/version keys", () => {
    const lock = [
      "lockfileVersion: '6.0'",
      "packages:",
      "  /next@14.0.0(react@18.2.0):",
      "    resolution: {}",
      "  /@scope/pkg@1.2.3:",
      "    resolution: {}",
      "  /legacy/4.5.6:",
      "    resolution: {}",
      "  /@old/scoped/7.8.9_react@18.2.0:",
    ].join("\n");

    expect(summarize(parsePnpmLock(lock))).toEqual([
      "npm:next@14.0.0 L3",
      "npm:@scope/pkg@1.2.3 L5",
      "npm:legacy@4.5.6 L7",
      "npm:@old/scoped@7.8.9 L9",
    ]);
  });
});

describe("parseYarnLock", () => {
  it("reads classic v1 entries", () => {
    const lock = [
      "# yarn lockfile v1",
      "",
      '"@babel/core@^7.0.0", "@babel/core@^7.12.3":',
      '  version "7.24.0"',
      '  resolved "https://registry.yarnpkg.com/..."',
      "",
      "lodash@^4.17.0:",
      '  version "4.17.15"',
    ].join("\n");

    expect(summarize(parseYarnLock(lock))).toEqual(["npm:@babel/core@7.24.0 L3", "npm:lodash@4.17.15 L7"]);
  });

  it("reads Berry entries and skips __metadata and workspaces", () => {
    const lock = [
      "__metadata:",
      "  version: 8",
      "",
      '"lodash@npm:^4.17.0":',
      "  version: 4.17.15",
      "",
      '"app@workspace:.":',
      "  version: 0.0.0-use.local",
    ].join("\n");

    expect(summarize(parseYarnLock(lock))).toEqual(["npm:lodash@4.17.15 L4"]);
  });
});

describe("parseBunLock", () => {
  it("reads name@version tuples from the packages map", () => {
    const lock = [
      "{",
      '  "lockfileVersion": 1,',
      '  "packages": {',
      '    "lodash": ["lodash@4.17.15", "", {}, "sha512-x"],',
      '    "@types/node": ["@types/node@22.0.0", "", {}, "sha512-y"],',
      "  }",
      "}",
    ].join("\n");

    expect(summarize(parseBunLock(lock))).toEqual(["npm:lodash@4.17.15 L4", "npm:@types/node@22.0.0 L5"]);
  });
});

describe("Python lockfiles", () => {
  it("reads poetry.lock / uv.lock package tables", () => {
    const lock = ["[[package]]", 'name = "Flask"', 'version = "2.0.1"', "", "[[package]]", 'name = "PyYAML"', 'version = "5.3"'].join("\n");

    expect(summarize(parsePythonTomlLock(lock))).toEqual(["PyPI:flask@2.0.1 L2", "PyPI:pyyaml@5.3 L6"]);
  });

  it("reads Pipfile.lock default and develop groups", () => {
    const lock = JSON.stringify({ default: { flask: { version: "==2.0.1" } }, develop: { black: { version: "==24.1.0" } } }, null, 4);

    expect(summarize(parsePipfileLock(lock)).map((entry) => entry.split(" ")[0])).toEqual(["PyPI:flask@2.0.1", "PyPI:black@24.1.0"]);
  });
});

describe("lockfileParserFor", () => {
  it("selects parsers by basename", () => {
    expect(lockfileParserFor("apps/web/package-lock.json")).toBe(parsePackageLock);
    expect(lockfileParserFor("pnpm-lock.yaml")).toBe(parsePnpmLock);
    expect(lockfileParserFor("yarn.lock")).toBe(parseYarnLock);
    expect(lockfileParserFor("bun.lock")).toBe(parseBunLock);
    expect(lockfileParserFor("poetry.lock")).toBe(parsePythonTomlLock);
    expect(lockfileParserFor("uv.lock")).toBe(parsePythonTomlLock);
    expect(lockfileParserFor("Pipfile.lock")).toBe(parsePipfileLock);
    expect(lockfileParserFor("package.json")).toBeUndefined();
  });
});
